CREATE TABLE #res (Base sysname, Tabla sysname, Columna sysname, Patron nvarchar(100), Filas bigint, LlavesJSON nvarchar(400));
DECLARE @b sysname, @t sysname, @col sysname, @sql nvarchar(max);
DECLARE k CURSOR LOCAL FAST_FORWARD FOR SELECT Base, Tabla, Columna FROM @c;
OPEN k; FETCH NEXT FROM k INTO @b, @t, @col;
WHILE @@FETCH_STATUS = 0
BEGIN
  SET @sql = N'
  ;WITH v AS (SELECT CONVERT(nvarchar(4000), ' + QUOTENAME(@col) + N', 126) AS v FROM ' + QUOTENAME(@b) + N'.dbo.' + QUOTENAME(@t) + N'),
  p AS (SELECT v, CASE
     WHEN v IS NULL THEN N''(nulo)''
     WHEN LTRIM(RTRIM(v)) = N'''' THEN N''(vacío)''
     WHEN LTRIM(v) LIKE N''{%'' AND ISJSON(v) = 1 THEN N''JSON objeto''
     WHEN LTRIM(v) LIKE N''[[]%'' AND ISJSON(v) = 1 THEN N''JSON lista''
     WHEN LTRIM(RTRIM(v)) NOT LIKE N''%[^0-9]%'' THEN N''dígitos x'' + CAST(LEN(LTRIM(RTRIM(v))) AS nvarchar(5))
     WHEN v LIKE N''[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]T[0-9][0-9]:%[+-][0-9][0-9]:[0-9][0-9]'' THEN N''fecha ISO con zona''
     WHEN v LIKE N''[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]T%'' THEN N''fecha ISO sin zona''
     WHEN v LIKE N''[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9] [0-9]%'' THEN N''fecha con espacio''
     WHEN v LIKE N''[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]'' THEN N''fecha sin hora''
     WHEN v LIKE N''[0-9]%/%[0-9]'' AND v NOT LIKE N''%[^0-9/ :]%'' THEN N''fecha con barras''
     WHEN LTRIM(RTRIM(v)) NOT LIKE N''%[^0-9 .-]%'' THEN N''dígitos con separadores x'' + CAST(LEN(REPLACE(REPLACE(REPLACE(v, N'' '', N''''), N''-'', N''''), N''.'', N'''')) AS nvarchar(5))
     WHEN TRY_CONVERT(float, v) IS NOT NULL THEN N''número decimal''
     WHEN LOWER(LTRIM(RTRIM(v))) IN (N''true'', N''false'') THEN N''true/false''
     WHEN UPPER(REPLACE(REPLACE(REPLACE(LTRIM(RTRIM(v)), N'' '', N''''), N''-'', N''''), N''.'', N'''')) COLLATE Latin1_General_BIN LIKE N''[A-Z][A-Z][A-Z][0-9][0-9][0-9][0-9]%''
          AND SUBSTRING(UPPER(REPLACE(REPLACE(REPLACE(LTRIM(RTRIM(v)), N'' '', N''''), N''-'', N''''), N''.'', N'''')), 4, 50) NOT LIKE N''%[^0-9]%'' THEN N''circuito''
     WHEN v LIKE N''%@%.%'' THEN N''correo''
     ELSE N''texto (largo '' + CASE WHEN LEN(v) <= 20 THEN N''<=20'' WHEN LEN(v) <= 100 THEN N''21-100'' ELSE N''>100'' END + N'')'' END AS Patron
     FROM v)
  INSERT #res (Base, Tabla, Columna, Patron, Filas, LlavesJSON)
  SELECT @b, @t, @col, Patron, COUNT_BIG(*),
         CASE WHEN Patron = N''JSON objeto'' THEN (SELECT TOP 1 STRING_AGG(j.[key], N'','') FROM (SELECT TOP 1 v FROM p p2 WHERE p2.Patron = N''JSON objeto'') x CROSS APPLY OPENJSON(x.v) j) END
  FROM p GROUP BY Patron;';
  BEGIN TRY
    EXEC sp_executesql @sql, N'@b sysname, @t sysname, @col sysname', @b, @t, @col;
  END TRY
  BEGIN CATCH
    INSERT #res VALUES (@b, @t, @col, N'ERROR: ' + LEFT(ERROR_MESSAGE(), 80), 0, NULL);
  END CATCH
  FETCH NEXT FROM k INTO @b, @t, @col;
END
CLOSE k; DEALLOCATE k;
SELECT Base, Tabla, Columna, Patron, Filas, LlavesJSON FROM #res ORDER BY Base, Tabla, Columna, Filas DESC;
